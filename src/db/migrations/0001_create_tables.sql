CREATE TABLE book_purpose (
  id integer PRIMARY KEY,
  code varchar(64) NOT NULL UNIQUE,
  name varchar(150) NOT NULL,
  description text,
  created_date timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE transaction_state (
  id integer PRIMARY KEY,
  code varchar(50) NOT NULL UNIQUE,
  name varchar(100) NOT NULL,
  description text,
  created_date timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE journal_transaction (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uuid_token varchar(36) NOT NULL,
  transaction_type_id integer NOT NULL,
  from_account_id integer,
  to_account_id integer,
  transaction_hash varchar(255),
  journal_transaction_state integer NOT NULL,
  idempotency_token varchar(36) NOT NULL UNIQUE,
  business_post_date_time timestamptz,
  created_date timestamptz NOT NULL DEFAULT now(),
  created_by integer,
  updated_date timestamptz,
  updated_by integer
);

CREATE INDEX idx_journal_transaction_uuid_token ON journal_transaction (uuid_token);

CREATE INDEX idx_journal_transaction_transaction_hash ON journal_transaction (transaction_hash);

CREATE TABLE journal_transaction_history (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  history_transaction_type_id integer NOT NULL,
  journal_transaction_id bigint NOT NULL REFERENCES journal_transaction (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
  journal_transaction_state integer NOT NULL,
  transaction_hash varchar(255),
  transaction_state_id integer REFERENCES transaction_state (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
  created_date timestamptz NOT NULL DEFAULT now(),
  created_by integer
);

CREATE INDEX idx_journal_transaction_history_journal_transaction ON journal_transaction_history (journal_transaction_id, id);

CREATE TABLE book (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar(255),
  book_purpose_id integer NOT NULL REFERENCES book_purpose (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
  transaction_state_id integer REFERENCES transaction_state (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
  client_id integer NOT NULL,
  account_id integer NOT NULL,
  asset_id integer NOT NULL,
  asset_type_id integer NOT NULL,
  asset_ticker varchar(50) NOT NULL,
  amount numeric(65, 0) NOT NULL DEFAULT 0,
  last_sequence_no bigint NOT NULL DEFAULT 0,
  wallet_type_id integer NOT NULL,
  address varchar(255),
  created_date timestamptz NOT NULL DEFAULT now(),
  created_by integer,
  updated_date timestamptz,
  updated_by integer
);

CREATE UNIQUE INDEX idx_unique_book ON book (client_id, account_id, asset_type_id, wallet_type_id, book_purpose_id, transaction_state_id) NULLS NOT DISTINCT;

CREATE TABLE book_posting (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uuid_token uuid NOT NULL UNIQUE,
  journal_transaction_id bigint NOT NULL REFERENCES journal_transaction (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
  book_id integer NOT NULL REFERENCES book (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
  amount numeric(65, 0) NOT NULL DEFAULT 0,
  book_posting_purpose_id integer NOT NULL,
  asset_type_id integer,
  sequence_no bigint NOT NULL DEFAULT 0,
  idempotency_token varchar(64) NOT NULL,
  business_post_date_time timestamptz,
  created_date timestamptz NOT NULL DEFAULT now(),
  created_by integer
);

CREATE UNIQUE INDEX uk_book_posting_book_sequence ON book_posting (book_id, sequence_no);

CREATE UNIQUE INDEX uk_book_posting_idempotency_token ON book_posting (idempotency_token);

CREATE INDEX idx_book_posting_journal_transaction ON book_posting (journal_transaction_id);

CREATE TABLE book_history (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  history_transaction_type_id integer NOT NULL,
  book_id integer NOT NULL REFERENCES book (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
  book_posting_id bigint REFERENCES book_posting (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
  amount numeric(65, 0) NOT NULL DEFAULT 0,
  last_sequence_no bigint NOT NULL DEFAULT 0,
  created_date timestamptz NOT NULL DEFAULT now(),
  created_by integer
);

CREATE INDEX idx_book_history_book ON book_history (book_id, id);

CREATE TABLE inbox_event (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_id varchar(64) NOT NULL,
  kind integer NOT NULL,
  source varchar(64),
  ordering_key varchar(255) NOT NULL,
  target_state_id integer,
  payload jsonb NOT NULL,
  payload_hash varchar(64) NOT NULL,
  status integer NOT NULL,
  delivery_count integer NOT NULL DEFAULT 1,
  attempts integer NOT NULL DEFAULT 0,
  journal_transaction_id bigint,
  last_error text,
  first_received_at timestamptz NOT NULL,
  last_received_at timestamptz NOT NULL,
  next_attempt_at timestamptz NOT NULL,
  applied_at timestamptz
);

CREATE UNIQUE INDEX uk_inbox_event_event_id ON inbox_event (event_id);

CREATE INDEX idx_inbox_event_ready ON inbox_event (status, next_attempt_at);

CREATE INDEX idx_inbox_event_journal_transaction ON inbox_event (journal_transaction_id);

CREATE INDEX idx_inbox_event_ordering_key ON inbox_event (ordering_key);

CREATE TABLE outbox_event (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  aggregate varchar(64) NOT NULL,
  event_type integer NOT NULL,
  state_id integer NOT NULL,
  attempt integer NOT NULL DEFAULT 1,
  payload jsonb NOT NULL,
  status integer NOT NULL,
  attempts integer NOT NULL DEFAULT 0,
  next_attempt_at timestamptz NOT NULL,
  last_error text,
  created_at timestamptz NOT NULL,
  published_at timestamptz
);

CREATE UNIQUE INDEX uk_outbox_event_aggregate_type_state_attempt ON outbox_event (aggregate, event_type, state_id, attempt);

CREATE INDEX idx_outbox_event_ready ON outbox_event (status, next_attempt_at);
